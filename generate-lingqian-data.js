// ======= 1. 观音灵签 100签 (从part1提取) =======
const guanyinItems = [];
// 从 part1.ts 解析
const part1 = fs.readFileSync('src/app/lingqian/lingqian-data-part1.ts', 'utf8');
const gMatch = part1.match(/const guanyin[\s\S]*?items:\s*\[([\s\S]*?)\]\s*\}/);
if (gMatch) {
  const block = gMatch[1];
  const items = block.split('}, {');
  items.forEach((item, i) => {
    try {
      const clean = i === 0 ? item : '{' + item;
      const endClean = i === items.length - 1 ? clean : clean + '}';
      // simple parse
      const idM = endClean.match(/id:(\d+)/);
      const titleM = endClean.match(/title:'([^']*)'/);
      const levelM = endClean.match(/level:'([^']*)'/);
      const poemM = endClean.match(/poem:'([^']*)'/);
      const verdictM = endClean.match(/verdict:'([^']*)'/);
      const meaningM = endClean.match(/meaning:'([^']*)'/);
      if (idM) guanyinItems.push({
        id: parseInt(idM[1]),
        title: titleM ? titleM[1] : '',
        level: levelM ? levelM[1] : '中平',
        poem: poemM ? poemM[1] : '',
        verdict: verdictM ? verdictM[1] : '',
        meaning: meaningM ? meaningM[1] : ''
      });
    } catch(e) {}
  });
}

