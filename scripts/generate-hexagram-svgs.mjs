// Simple SVG hexagram renderer
function renderHexagram(lines, name, title, width=120, height=140) {
  const lineHeight = 14
  const gap = 4
  const startY = 20
  const lineWidth = 80
  const yangColor = '#333'
  const yinColor = '#999'
  const indentOffset = 5 // yin line gap
  
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
  <rect width="${width}" height="${height}" fill="white" rx="8"/>
  <text x="${width/2}" y="16" text-anchor="middle" font-size="11" fill="#888" font-family="serif">${title}</text>\n`
  
  for (let i = 0; i < 6; i++) {
    const y = startY + i * (lineHeight + gap)
    const isYang = lines[i] === 1
    
    if (isYang) {
      // Solid line (阳爻)
      const x = (width - lineWidth) / 2
      svg += `  <rect x="${x}" y="${y}" width="${lineWidth}" height="6" rx="2" fill="${yangColor}"/>\n`
    } else {
      // Broken line (阴爻)
      const segWidth = (lineWidth - indentOffset) / 2
      const x1 = (width - lineWidth) / 2
      const x2 = x1 + segWidth + indentOffset
      svg += `  <rect x="${x1}" y="${y}" width="${segWidth}" height="6" rx="2" fill="${yinColor}"/>\n`
      svg += `  <rect x="${x2}" y="${y}" width="${segWidth}" height="6" rx="2" fill="${yinColor}"/>\n`
    }
  }
  
  svg += '</svg>'
  return svg
}

