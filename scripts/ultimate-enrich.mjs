// 主流程
// ──────────────────────────────────────

function main() {
  const files = readdirSync(QUEUE_DIR)
    .filter(f => f.startsWith('name-') && f.endsWith('.txt'))
    .sort();
  
  console.log(`总 ${files.length} 篇文章`);
  
  let rewritten = 0;
  let skipped = 0;
  let errors = 0;
  
  for (let i = 0; i < files.length; i++) {
    const f = files[i];
    const zi = f.replace('name-', '').replace('.txt', '');
    const oldContent = readFileSync(join(QUEUE_DIR, f), 'utf-8');
    
    // 提取笔画和五行
    const sMatch = oldContent.match(/（(\d+)画/);
    const stroke = sMatch ? parseInt(sMatch[1]) : (() => {
      const s2 = oldContent.match(/(\d+)画/);
      return s2 ? parseInt(s2[1]) : 0;
    })();
    
    const elMatch = oldContent.match(/五行属([一-鿿]+)/) || oldContent.match(/五行([一-鿿]+)吉字/);
    const elName = elMatch ? elMatch[1] : '';
    
    // 判断是否为金行≤5画的深度文章
    const isDeepHandcrafted = DICT[zi] && (
      oldContent.includes('《说文解字》云：') || 
      oldContent.includes('云："') ||
      oldContent.length > 2000
    );
    
    if (isDeepHandcrafted && DICT[zi]) {
      skipped++;
      continue;
    }
    
    if (!elName || !stroke || stroke === 0) {
      console.log(`跳过 ${zi}: 无法提取笔画(${stroke})或五行(${elName})`);
      skipped++;
      continue;
    }
    
    // 字典中有这个字 → 用深度词典数据
    const newContent = generateArticle(zi, stroke, elName, DICT[zi]);
    
    writeFileSync(join(QUEUE_DIR, f), newContent, 'utf-8');
    rewritten++;
    
    if ((i + 1) % 400 === 0) {
      console.log(`进度: ${i+1}/${files.length}, 已重写: ${rewritten}, 跳过: ${skipped}`);
    }
  }
  
  console.log(`\n完成! 总${files.length}篇`);
  console.log(`  重写: ${rewritten}篇`);
  console.log(`  跳过(已有深度): ${skipped}篇`);
  console.log(`  错误: ${errors}篇`);
  
  // 最终质量检查
  console.log('\n=== 质量抽样检查 ===');
  
  const checkFiles = ['name-成.txt', 'name-林.txt', 'name-浩.txt', 'name-睿.txt'];
  for (const cf of checkFiles) {
    const path = join(QUEUE_DIR, cf);
    if (!existsSync(path)) continue;
    const content = readFileSync(path, 'utf-8');
    const hasSW = content.includes('《说文解字》云');
    const hasGY = content.includes('《广韵》');
    const hasQuote = content.includes('《诗');
    const hasTemplateGarbage = content.includes('从古老字形到今天的写法') || content.includes('有内在的关联');
    const hasEllipsis = content.includes('……');
    const quality = (hasSW ? '✅《说文》' : '❌无说文') + ' ' + 
                    (hasGY ? '✅《广韵》' : '❌无广韵') + ' ' +
                    (hasQuote ? '✅名句' : '❌无名句') + ' ' +
                    (hasTemplateGarbage ? '❌模板废话' : '✅无废话') + ' ' +
                    (hasEllipsis ? '❌有占位符' : '✅无占位符');
    console.log(`  ${cf.replace('.txt','')}: ${quality}`);
  }
}

// import missing existsSync
import { existsSync } from 'fs';

main();
