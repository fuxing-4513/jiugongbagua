// ── 主逻辑 ──
const raw = JSON.parse(readFileSync(DATA_FILE, 'utf-8'));
const dreams = Array.isArray(raw) ? raw : raw.dreams;

let overridden = 0, sceneFixed = 0;

for (const d of dreams) {
  // 1) 特殊词条精准覆盖（仅当该条不是手写精写层时）
  const ov = OVERRIDES[d.keyword];
  if (ov && ov.modern && !d.premiumSource) {
    d.modern = ov.modern;
    d.detail = ov.detail;
    d.psychologyNote = ov.psychologyNote;
    overridden++;
    continue;
  }

  // 2) 场景标签修复：把生硬的【涉及"X"】改为自然表达，并过滤无关场景
  if (d.detail && d.detail.includes('【涉及')) {
    // 提取原句干（去掉场景包装）
    const innerTexts = [...d.detail.matchAll(/【涉及"[^"]*"】([^；]+)；/g)].map(m => m[1]);
    if (innerTexts.length) {
      let rebuilt = `分场景细看：`;
      innerTexts.forEach((t, i) => {
        rebuilt += `${i === 0 ? '' : ''}◆ ${t}。`;
      });
      rebuilt += ` 若梦中的情境与上述任何一条吻合，优先采用那条解读；都不吻合时，回到梦中情绪本身：它是这条解读最可靠的钥匙。`;
      d.detail = rebuilt;
      sceneFixed++;
    }
  }
}

console.log(`特殊词条覆盖: ${overridden} 条`);
console.log(`场景表达优化: ${sceneFixed} 条`);

if (Array.isArray(raw)) writeFileSync(DATA_FILE, JSON.stringify(raw), 'utf-8');
else writeFileSync(DATA_FILE, JSON.stringify({ ...raw, dreams }), 'utf-8');
console.log(`文件大小: ${(JSON.stringify(dreams).length / 1024 / 1024).toFixed(2)} MB`);
