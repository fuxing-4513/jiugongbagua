// ── 工具函数 ──
function hashStr(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = ((h << 5) - h) + s.charCodeAt(i), h |= 0;
  return Math.abs(h);
}
const pick = (arr, seed) => arr[seed % arr.length];

// ── 主逻辑 ──
const raw = JSON.parse(readFileSync(DATA_FILE, 'utf-8'));
const dreams = Array.isArray(raw) ? raw : raw.dreams;

let upgraded = 0, skippedPremium = 0;
for (const d of dreams) {
  // 跳过手写精写层
  if (d.psychologyNote) { skippedPremium++; continue; }

  const modernLen = (d.modern || '').length;
  const detailLen = (d.detail || '').length;
  // 只处理一句话级词条
  if (modernLen + detailLen > 120) continue;

  const sym = SYMBOLISM[d.category] || SYMBOLISM['其他'];
  const seed = hashStr(d.keyword + d.category);

  // ── 生成 modern（总述）──
  const baseMeaning = (d.modern && d.modern.length > 10) ? d.modern : (d.detail || '');
  const modern = `${baseMeaning.replace(/[。\s]*$/, '')}。从象征层面看，${d.title}的核心意象是${sym.core}。${sym.lens}——因此这个梦首先是一面镜子：它映照的不是吉凶祸福的定数，而是你潜意识对相关领域现状的实时评估。`;

  // ── 生成 detail（分场景）──
  const sceneKeys = Object.keys(sym.scenes);
  const s1 = pick(sceneKeys, seed), s2 = pick(sceneKeys, seed + 7), s3 = pick(sceneKeys, seed + 13);
  const kwHit = sceneKeys.filter(k => d.keyword.includes(k) || (d.title || '').includes(k));
  const chosen = [...new Set([...(kwHit.length ? [kwHit[0]] : []), s1, s2, s3])].slice(0, 4);

  let detail = `分场景细看：`;
  for (const k of chosen) {
    detail += `【涉及"${k}"】${sym.scenes[k]}；`;
  }
  detail += `【总体基调】结合梦中情绪判断吉凶走向：梦中平静从容，多为顺势信号；梦中焦虑惊惶，则是现实压力的善意提醒。建议醒来后回顾近况，对照梦中情境找到那个最贴合的解读。`;

  // ── 生成 psychologyNote ──
  const moodText = d.mood ? `此梦伴随"${d.mood}"的情绪基调` : '此梦的情绪底色值得留意';
  const psychologyNote = `${moodText}。${sym.lens}。心理学视角提醒：解梦的价值不在预言，而在自我觉察——把梦当作潜意识寄来的一封信，读它，然后回到现实做出更清醒的选择。`;

  d.modern = modern;
  d.detail = detail;
  d.psychologyNote = psychologyNote;
  upgraded++;
}

console.log(`总条目: ${dreams.length}`);
console.log(`跳过手写精写: ${skippedPremium} 条`);
console.log(`本次扩写: ${upgraded} 条`);

// 写回
if (Array.isArray(raw)) writeFileSync(DATA_FILE, JSON.stringify(raw), 'utf-8');
else writeFileSync(DATA_FILE, JSON.stringify({ ...raw, dreams }), 'utf-8');

const sizeMB = (JSON.stringify(dreams).length / 1024 / 1024).toFixed(2);
console.log(`文件大小: ${sizeMB} MB`);
