// ── 主生成函数 ──

export function generatePsychology(dream: DreamInput): PsychologyInterpretation {
  const { keyword, category, tags, mood } = dream
  const s = seed(keyword, category)
  const s2 = seed(keyword + (tags[0] || ''), category)

  // 检查是否有关键词专属解读 (优先)
  const specialistKey = Object.keys(KEYWORD_SPECIALISTS).find(k =>
    keyword.includes(k) || k.includes(keyword) ||
    tags.some(t => t.includes(k) || k.includes(t))
  )
  if (specialistKey) {
    const sp = KEYWORD_SPECIALISTS[specialistKey](keyword, tags, mood, s)
    if (sp) {
      return {
        jung: sp.jung || generateJung(keyword, category, tags, mood, s2),
        freud: sp.freud || generateFreud(keyword, category, tags, mood, s2),
        gestalt: sp.gestalt || generateGestalt(keyword, category, tags, mood, s2),
        summary: sp.summary || generateSummary(keyword, category, tags, mood, s2),
      }
    }
  }

  // 通用分类生成
  return {
    jung: generateJung(keyword, category, tags, mood, s),
    freud: generateFreud(keyword, category, tags, mood, s2),
    gestalt: generateGestalt(keyword, category, tags, mood, s + 7),
    summary: generateSummary(keyword, category, tags, mood, s2 + 13),
  }
}

