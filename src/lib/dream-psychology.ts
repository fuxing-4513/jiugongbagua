// ── 哈希辅助 ──
function hashStr(s: string): number {
  let h = 0
  for (let i = 0; i < s.length; i++) {
    h = ((h << 5) - h) + s.charCodeAt(i)
    h |= 0
  }
  return Math.abs(h)
}

function seed(kw: string, cat: string): number {
  return hashStr(kw + '|' + cat) * 13 + 7
}

function pick<T>(arr: T[], s: number): T {
  return arr[Math.abs(s) % arr.length]
}

