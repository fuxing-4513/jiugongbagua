function getStrokes(char: string): number {
  if (CHAR_STROKES[char] !== undefined) return CHAR_STROKES[char];
  return Math.max(1, Math.round(char.length * 3));
}

export function getWuxing(num: number): string {
  return NUM_WUXING[num % 10] ?? '水';
}

function getNumberFortune(num: number): NumberFortune {
  let r = num;
  while (r > 81) r -= 81;
  return NUMBER_FORTUNE[r] ?? NUMBER_FORTUNE[80]!;
}

export function calcNameWuge(firstName: string, lastName: string): WugeResult {
  const sum = (s: string) => s.split('').reduce((a,c) => a + getStrokes(c), 0);
  const surSum = sum(lastName);
  const firSum = sum(firstName);
  const surLast = getStrokes(lastName[lastName.length-1] ?? '');
  const firFirst = getStrokes(firstName[0] ?? '');

  const tianNum = surSum + 1;
  const renNum = surLast + firFirst;
  const diNum = firSum + 1;
  const zongNum = surSum + firSum;
  const waiNum = zongNum - renNum + 1;

  const mk = (n: number): WugeGrid => {
    const f = getNumberFortune(n);
    return { num:n, wuxing:getWuxing(n), ji:f.ji, desc:f.desc };
  };
  const tian = mk(tianNum), ren = mk(renNum), di = mk(diNum);
  const zong = mk(zongNum), wai = mk(waiNum);
  const sancai = `${tian.wuxing}${ren.wuxing}${di.wuxing}`;

  const sm: Record<JiType,number> = { '大吉':85, '中吉':60, '凶':25 };
  const score = Math.round((sm[ren.ji]??50) * 0.6 + (sm[zong.ji]??50) * 0.4);

  return { tian, ren, di, zong, wai, sancai, score };
}

