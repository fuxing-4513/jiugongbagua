const SHA_STARS = ['擎羊', '陀罗', '火星', '铃星', '地空', '地劫']

// ── 主入口 ──
export function polishPattern(p: { name: string; level: string; description: string }): PatternPolish {
  const hand = HAND_POLISH[p.name]
  if (hand) return hand

  const level = (['excellent', 'good', 'neutral', 'caution'].includes(p.level) ? p.level : 'neutral') as Level
  const desc = p.description || ''

  // 提取出现的星曜
  const stars: string[] = []
  for (const s of Object.keys(STAR_TRAITS)) {
    if (desc.includes(s)) stars.push(s)
  }
  const ji = stars.filter(s => JI_STARS.includes(s))
  const sha = stars.filter(s => SHA_STARS.includes(s))
  const jiHua = desc.includes('化禄') || desc.includes('化权') || desc.includes('化科')
  const jiStar = desc.includes('化忌')

  // 性格特质
  let traits = LEVEL_TRAITS[level]
  if (stars.length > 0) {
    const starDesc = stars.slice(0, 4).map(s => STAR_TRAITS[s]).filter(Boolean).join('；')
    traits = `此格星曜组合：${starDesc}。` + traits
  }
  if (ji.length > 0) traits += '吉星拱照，贵人缘与助力明显。'
  if (sha.length > 0) traits += '煞星同会，性子偏烈、人生多磨，但韧性十足。'
  if (jiHua) traits += '吉化加持，才华得以显扬。'
  if (jiStar) traits += '有化忌牵动，内心常有功课与执念，需自我调适。'

  // 人生运势
  let fortune = LEVEL_FORTUNE[level]
  if (ji.length > 0 && level !== 'caution') fortune = '吉星同会，' + fortune
  if (sha.length > 0) fortune = '煞星相伴，' + fortune + '宜将「变动」视为机会，主动求变反能破局。'
  if (jiStar) fortune = '化忌所在之宫即人生功课，' + fortune

  // 人生指导
  const careers = stars.slice(0, 3).map(s => STAR_CAREER[s]).filter(Boolean)
  let guidance = LEVEL_GUIDANCE[level]
  if (careers.length > 0) guidance = `宜从事${[...new Set(careers)].join('、')}等方向。` + guidance
  if (sha.includes('擎羊') || sha.includes('火星')) guidance += '注意控制情绪与车速、谨防外伤。'
  if (sha.includes('陀罗')) guidance += '注意克服拖延，大事早规划。'
  if (sha.includes('地空') || sha.includes('地劫')) guidance += '理财宜守，谨防财来财去。'
  if (desc.includes('化忌')) guidance += '化忌之宫位须长期修炼，逢忌年大限宜守不宜攻。'

  return { traits, fortune, guidance }
}
