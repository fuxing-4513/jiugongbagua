/** 按分类获取书籍清单 */
export function getBooksByCategory(categoryId: string): BookMeta[] {
  return (bookCatalog as BookMeta[]).filter(b => b && b.category === categoryId)
}

/** 按 ID 查找书籍 */
export function findBook(id: string): BookMeta | undefined {
  return (bookCatalog as BookMeta[]).find(b => b && b.id === id)
}

/** 获取所有分类下的书籍统计 */
export function getCategoryStats(): Record<string, { total: number; complete: number }> {
  const stats: Record<string, { total: number; complete: number }> = {}
  for (const book of (bookCatalog as BookMeta[])) { if (!book) continue;
    if (!stats[book.category]) stats[book.category] = { total: 0, complete: 0 }
    stats[book.category].total++
    if (book.isComplete) stats[book.category].complete++
  }
  return stats
}
