【神将配合】

神者天将，将者月将。神将配合，各有所司。

神将相生，吉上加吉。神将相克，凶上添凶。
神吉将凶，外吉内凶。神凶将吉，外凶内吉。

神将皆吉，万事亨通。神将皆凶，诸事不利。

