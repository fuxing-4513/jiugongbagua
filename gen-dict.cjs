// CJK Unified Ideographs (U+4E00 to U+9FFF)
const CJK_START = 0x4E00;
const CJK_END = 0x9FFF;

// Generate stroke estimation based on Unicode range
// Real strokes vary, but we approximate
function approximateStroke(charCode) {
  const rel = (charCode - CJK_START) / (CJK_END - CJK_START);
  if (rel < 0.2) return Math.floor(rel * 40) + 1;  // ~1-8 strokes
  if (rel < 0.4) return Math.floor(rel * 60) + 3;   // ~3-24 strokes
  if (rel < 0.6) return Math.floor(rel * 80) + 5;   // ~5-48 strokes
  if (rel < 0.8) return Math.floor(rel * 100) + 8;  // ~8-80 strokes
  return Math.floor(rel * 120) + 12;                 // ~12-120 strokes
}

