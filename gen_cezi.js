// Generate interpretation based on character components
function genInterpretation(c, s, wx) {
  const hasHeart = '心忄'.split('').some(r => c.includes(r));
  const hasWater = '氵水雨'.split('').some(r => c.includes(r));
  const hasFire = '火灬'.split('').some(r => c.includes(r));
  const hasWood = '木林'.split('').some(r => c.includes(r));
  const hasGold = '金钅'.split('').some(r => c.includes(r));
  const hasEarth = '土'.split('').some(r => c.includes(r));
  const hasPerson = '亻人'.split('').some(r => c.includes(r));
  const hasMouth = '口'.split('').some(r => c.includes(r));
  const hasWalk = '辶走'.split('').some(r => c.includes(r));
  const hasRoof = '宀'.split('').some(r => c.includes(r));

  let interp = `${c}字，`;
  if (hasRoof) interp += '有安居之象，主家庭和睦家运兴隆。';
  else if (hasHeart) interp += '心字之旁，主心地善良情感丰富。';
  else if (hasWater) interp += '含水之象，主智慧通达财运如水。';
  else if (hasFire) interp += '含火之象，主人气旺盛热情似火。';
  else if (hasWood) interp += '含木之象，主生机勃勃向上生长。';
  else if (hasGold) interp += '含金之象，主财运亨通意志坚定。';
  else if (hasEarth) interp += '含土之象，主根基深厚稳重踏实。';
  else if (hasPerson) interp += '从人之旁，主人际关系融洽得众人助。';
  else if (hasMouth) interp += '含口之象，主口才出众善于表达。';
  else if (hasWalk) interp += '带走之底，主行动力强勇于前行。';
  else interp += '结构端正，主行事方正为人正直。';

  interp += `测到此字，五行属${wx}，${s}画。`;
  if (s <= 4) interp += '笔画简洁，主事态简单明了。';
  else if (s <= 8) interp += '笔画适中，主发展平稳。';
  else if (s <= 12) interp += '笔画较多，主需要付出努力。';
  else interp += '笔画繁多，主事务复杂需耐心处理。';

  return interp;
}

